def pos_encoding(length, dim, device, dtype):
    """Deterministic fixed sinusoidal temporal positions, no TEST fitting."""
    idx=torch.arange(length,dtype=dtype,device=device).unsqueeze(1)
    half=(dim+1)//2
    frequency=torch.exp(-math.log(10000.0)*torch.arange(
        half,dtype=dtype,device=device)/max(1,half-1))
    out=torch.cat((torch.sin(idx*frequency[None,:]),
                   torch.cos(idx*frequency[None,:])),dim=1)
    return out[:,:dim]


class PyramidalTokens(nn.Module):
    """Trainable multiscale patch features; fixed number of tokens per scale."""
    def __init__(self, channels, dim, bins=(8,16,24)):
        super().__init__()
        self.bins=tuple(bins)
        self.proj=nn.Linear(3*channels,dim)
        self.scale=nn.Parameter(torch.randn(len(self.bins),dim)*.02)
        self.norm=nn.LayerNorm(dim)
    def forward(self,x):
        y=x.transpose(1,2)
        dy=torch.abs(y[:,:,1:]-y[:,:,:-1]) if x.size(1)>1 else torch.zeros_like(y)
        out=[]
        for level,n in enumerate(self.bins):
            mu=F.adaptive_avg_pool1d(y,n).transpose(1,2)
            energy=F.adaptive_avg_pool1d(y.square(),n).clamp_min(1.e-8).sqrt().transpose(1,2)
            rough=F.adaptive_avg_pool1d(dy,n).transpose(1,2)
            token=self.proj(torch.cat((mu,energy,rough),dim=-1))
            token=token+self.scale[level]+pos_encoding(n,token.size(-1),
                device=x.device,dtype=x.dtype)
            out.append(token)
        return self.norm(torch.cat(out,dim=1))


class SparseMechanismBlock(nn.Module):
    """Two-route, concept-gated attention with truly local and O(N*K) memory.

    Local route uses an explicit window with width 2*radius+1, rather than
    computing dense N*N attention and then masking. The global route uses
    learned K slots attending to N tokens and tokens attending back to K slots.
    The mixture gate is generated by analytic concept embeddings.
    """
    def __init__(self,dim=64,heads=4,slots=6,radius=3):
        super().__init__()
        if dim%heads:raise ValueError("dim must be divisible by heads")
        self.dim,self.heads,self.width,self.slots=dim,heads,dim//heads,slots
        self.radius=radius
        self.pre=nn.LayerNorm(dim)
        self.qkv=nn.Linear(dim,dim*3,bias=False)
        self.slot_queries=nn.Parameter(torch.randn(slots,dim)*.02)
        self.slot_context=nn.Linear(dim,dim,bias=False)
        self.router=nn.Sequential(nn.Linear(dim,dim),nn.GELU(),
                                  nn.Linear(dim,heads))
        self.out=nn.Linear(dim,dim)
        self.ffn_norm=nn.LayerNorm(dim)
        self.ffn=nn.Sequential(nn.Linear(dim,dim*3),nn.GELU(),
                               nn.Linear(dim*3,dim))
        self.scale=nn.Parameter(torch.full((1,),.50))

    def forward(self,x,context):
        B,N,D=x.shape;H=self.heads;W=self.width
        qkv=self.qkv(self.pre(x)).reshape(B,N,3,H,W).permute(2,0,3,1,4)
        q,k,v=qkv.unbind(dim=0)
        offset=torch.arange(-self.radius,self.radius+1,device=x.device)
        position=torch.arange(N,device=x.device)
        index=position[:,None]+offset[None,:]
        invalid=(index<0)|(index>=N)
        index=index.clamp(0,N-1)
        near_k=k[:,:,index,:]   # (B,H,N,window,W)
        near_v=v[:,:,index,:]
        attn=(q.unsqueeze(-2)*near_k).sum(-1)/math.sqrt(W)
        attn=attn.masked_fill(invalid[None,None,:,:],-1.e4)
        local=(attn.softmax(dim=-1).unsqueeze(-1)*near_v).sum(-2)

        slot=(self.slot_queries[None,:,:]+self.slot_context(
            context)[:,None,:]).reshape(B,self.slots,H,W).permute(0,2,1,3)
        s2t=(slot@k.transpose(-1,-2))/math.sqrt(W)
        memory=s2t.softmax(dim=-1)@v
        t2s=(q@memory.transpose(-1,-2))/math.sqrt(W)
        global_view=t2s.softmax(dim=-1)@memory
        gate=torch.sigmoid(self.router(context))[:,:,None,None]
        blended=(1-gate)*local+gate*global_view
        mixed=blended.transpose(1,2).reshape(B,N,D)
        x=x+self.scale.tanh()*self.out(mixed)
        x=x+self.scale.tanh()*self.ffn(self.ffn_norm(x))
        return x,gate[:, :, 0, 0]


class DenseAttentionBlock(nn.Module):
    """Ordinary Transformer control with identical tokens and learning budget."""
    def __init__(self,dim=64,heads=4,slots=6,radius=3):
        super().__init__()
        self.layer=nn.TransformerEncoderLayer(
            d_model=dim,nhead=heads,dim_feedforward=dim*3,
            dropout=0.,activation="gelu",batch_first=True,norm_first=True)
    def forward(self,x,context):
        return self.layer(x),x.new_zeros((x.shape[0],1))


class ConceptPooledTokens(nn.Module):
    def __init__(self,dim):
        super().__init__()
        self.key=nn.Linear(dim,dim)
        self.query=nn.Linear(dim,dim)
        self.readout=nn.Sequential(nn.Linear(2*dim,dim),
            nn.LayerNorm(dim),nn.GELU())
    def forward(self,tokens,context):
        query=self.query(context)[:,None,:]
        attention=torch.softmax((query*self.key(tokens)).sum(-1)/
                                math.sqrt(tokens.shape[-1]),dim=-1)
        summary=torch.einsum("bn,bnd->bd",attention,tokens)
        return self.readout(torch.cat((summary,tokens.mean(1)),dim=-1))


class MESARouterFormer(nn.Module):
    def __init__(self,channels,dim=64,depth=2,heads=4,slots=6,radius=3,
                 attention="routed",bins=(8,16,24)):
        super().__init__()
        self.channels=channels;self.attention=attention
        self.raw_tokens=PyramidalTokens(channels,dim,bins)
        self.shape_tokens=PyramidalTokens(channels,dim,bins)
        self.raw_context=nn.Sequential(nn.Linear(3*channels,dim),
                                        nn.LayerNorm(dim),nn.GELU())
        self.shape_context=nn.Sequential(nn.Linear(2*channels,dim),
                                          nn.LayerNorm(dim),nn.GELU())
        cls=SparseMechanismBlock if attention=="routed" else DenseAttentionBlock
        if attention not in ("routed","dense"):raise ValueError(attention)
        self.raw_layers=nn.ModuleList([cls(dim,heads,slots,radius) for _ in range(depth)])
        self.shape_layers=nn.ModuleList([cls(dim,heads,slots,radius) for _ in range(depth)])
        self.raw_pool=ConceptPooledTokens(dim)
        self.shape_pool=ConceptPooledTokens(dim)
        self.concept_head=nn.Sequential(nn.Linear(dim,dim),nn.GELU(),
                                       nn.Linear(dim,3*channels))
        self.shape_head=nn.Sequential(nn.Linear(dim,dim),nn.GELU(),
                                     nn.Linear(dim,2*channels))
        self.freq_head=nn.Linear(dim,8*channels)

    def forward(self,x):
        shape,concept=torch_decompose(x)
        # An affine change modifies the raw stream context but cannot
        # enter the shape stream's conditioning vector.
        shape_concept=shape_harmonic_targets(x)
        cr=self.raw_context(concept)
        cs=self.shape_context(shape_concept)
        raw_tokens=self.raw_tokens(x)
        shape_tokens=self.shape_tokens(shape)
        gates=[]
        for raw_block,shape_block in zip(self.raw_layers,self.shape_layers):
            raw_tokens,gate_raw=raw_block(raw_tokens,cr)
            shape_tokens,gate_shape=shape_block(shape_tokens,cs)
            gates.append((gate_raw,gate_shape))
        zr=self.raw_pool(raw_tokens,cr)
        zs=self.shape_pool(shape_tokens,cs)
        return dict(raw=zr,shape=zs,concept=concept,
                    concept_pred=self.concept_head(zr),
                    shape_concept_pred=self.shape_head(zs),
                    freq_pred=self.freq_head(zs),
                    route_gates=gates)


def fit_ssl(x_train,seed,mechanism=True,attention="routed",
            epochs=10,dim=64,depth=2,lr=.0008):
    torch.manual_seed(int(seed));np.random.seed(int(seed))
    data=torch.as_tensor(x_train,dtype=torch.float32)
    net=MESARouterFormer(data.shape[-1],dim=dim,depth=depth,
                          attention=attention)
    opt=torch.optim.AdamW(net.parameters(),lr=lr,weight_decay=.0001)
    tau=torch.linspace(-1.,1.,data.shape[1],dtype=torch.float32)[None,:,None]
    timeharm=torch.linspace(0.,2*math.pi,data.shape[1],dtype=torch.float32)
    history=[]
    for epoch in range(epochs):
        net.train()
        lr_factor=.12+.88*.5*(1+math.cos(math.pi*epoch/max(1,epochs-1)))
        for group in opt.param_groups:group["lr"]=lr*lr_factor
        losses=[]
        for ids in torch.randperm(len(data)).split(48):
            x=data[ids]
            # Exactly the same view-generation RNG stream in both arms.
            masked=torch.rand_like(x)<.12
            disturbance=x+.045*torch.randn_like(x)
            view=torch.where(masked,torch.zeros_like(x),disturbance)
            clean=net(x); aug=net(view)
            off=.25*torch.randn((len(x),1,x.shape[2]))
            trend=.25*torch.randn((len(x),1,x.shape[2]))
            affine=net(x+off+tau*trend)
            sine=.25*torch.randn((len(x),1,x.shape[2]))
            harmonic=x+sine*torch.sin(timeharm)[None,:,None]
            altered=net(harmonic)
            # Core SSL objectives are the same in generic and MESA variants.
            shape_consistency=(1-F.cosine_similarity(
                clean["shape"],aug["shape"]).mean())
            raw_consistency=1-F.cosine_similarity(
                clean["raw"],aug["raw"]).mean()
            affine_consistency=1-F.cosine_similarity(
                clean["shape"],affine["shape"]).mean()
            variance=sum(F.relu(.45-clean[k].std(dim=0,unbiased=False)).mean()
                         for k in ("raw","shape"))
            spectrum=F.smooth_l1_loss(clean["freq_pred"],band_spectrum(x))
            loss=.24*shape_consistency+.12*raw_consistency
            loss=loss+.17*affine_consistency+.08*variance+.35*spectrum
            # Direct gradients to both learned streams; analytic concept
            # targets provide a checked counterfactual mechanism ablation.
            raw_target=clean["concept"]
            raw_delta=affine["concept"]-clean["concept"]
            shape_target=shape_harmonic_targets(x)
            harm_target=shape_harmonic_targets(harmonic)
            concept_loss=F.smooth_l1_loss(clean["concept_pred"],raw_target)
            raw_equiv=F.smooth_l1_loss(
                affine["concept_pred"]-clean["concept_pred"],raw_delta)
            shape_loss=F.smooth_l1_loss(
                clean["shape_concept_pred"],shape_target)
            shape_equiv=F.smooth_l1_loss(
                altered["shape_concept_pred"]-clean["shape_concept_pred"],
                harm_target-shape_target)
            loss=loss+float(mechanism)*(.30*concept_loss+.18*raw_equiv+
                                       .25*shape_loss+.20*shape_equiv)
            if not torch.isfinite(loss):raise FloatingPointError("Nonfinite loss")
            opt.zero_grad(set_to_none=True)
            loss.backward()
            torch.nn.utils.clip_grad_norm_(net.parameters(),2.)
            opt.step()
            losses.append(float(loss.detach().cpu()))
        history.append(float(np.mean(losses)))
    return net.eval(),history


def custom_fit(K,idx,y,classes,patterns):
    """Same TRAIN-only 3-mode exact LOO criterion as prior MESA dual chart."""
    Y=(y[idx,None]==classes[None,:]).astype(float)
    lab=y[idx]
    candidates=[]
    for weights in patterns:
        gram=sum(w*K[k]["train"] for k,w in weights.items())
        for ridge in RIDGES:
            inv=np.linalg.solve(gram+ridge*np.eye(len(idx)),np.eye(len(idx)))
            alpha=inv@Y
            diag=np.maximum(np.diag(inv),1.e-12)
            loo=[Y-alpha/diag[:,None]]
            for j in (0,1):
                cross=sum(w*K[k]["probe"][j] for k,w in weights.items())
                loo.append(cross@alpha-
                    (np.diag(cross@inv)/diag)[:,None]*alpha)
            metrics=[float(f1_score(lab,classes[np.argmax(v,axis=1)],
                        average="macro",zero_division=0)) for v in loo]
            score=.40*metrics[0]+.38*metrics[1]+.22*metrics[2]-.008*(len(weights)-1)
            candidates.append(dict(objective=float(score),weights=weights,
                ridge=ridge,coef=alpha,cv_f1=metrics,loo=loo))
    return sorted(candidates,key=lambda c:(
        -c["objective"],len(c["weights"]),c["ridge"],
        tuple(sorted(c["weights"].items()))))[0]


def model_candidates(prefix,hybrid=False):
    raw=f"{prefix}_raw"; shape=f"{prefix}_shape"
    base=[{raw:1.},{shape:1.},{raw:1.,shape:1.},
          {raw:1.,shape:1.,"stats":.1},{shape:1.,"stats":.1}]
    if not hybrid:return base
    return [
        {"rawMR":1.},{"shapeMR":1.},
        {"rawMR":1.,"shapeMR":1.},
        {"rawMR":1.,"shapeMR":1.,raw:.10},
        {"rawMR":1.,"shapeMR":1.,shape:.10},
        {"rawMR":1.,"shapeMR":1.,raw:.30,shape:.30},
        {"rawMR":1.,raw:.4,"stats":.08},
        {"shapeMR":1.,shape:.4},
        {"rawMR":.5,"shapeMR":1.,"stats":.05},
    ]


def numerical_tests():
    rng=np.random.default_rng(882)
    x=rng.normal(size=(3,97,2)).astype("float32")
    shifted=generate_affine_shift(x,11,1.2)
    for variant in ("routed","dense"):
        net=MESARouterFormer(2,dim=32,depth=2,heads=4,slots=4,
                             attention=variant).eval()
        xa=torch.as_tensor(x);ya=torch.as_tensor(shifted)
        with torch.no_grad():
            out=net(xa);other=net(ya)
        assert out["raw"].shape==(3,32) and out["shape"].shape==(3,32)
        assert out["concept_pred"].shape==(3,6)
        assert out["shape_concept_pred"].shape==(3,4)
        shape_error=(out["shape"]-other["shape"]).abs().max().item()
        if shape_error>2.e-4:
            raise AssertionError(f"Shape branch lost affine invariance: {shape_error}")
        concept_error=(out["concept"]-other["concept"]).abs().mean().item()
        if concept_error<.01:raise AssertionError("Raw concepts unexpectedly invariant")
    # Explicit gradient test: concept-routed global slots, local attention,
    # and BOTH towers must influence a scalar objective.
    net=MESARouterFormer(2,dim=32,depth=2,heads=4,slots=4)
    z=net(torch.as_tensor(x))
    value=(z["raw"].square().mean()+z["shape"].square().mean()+
           z["concept_pred"].square().mean()+
           z["shape_concept_pred"].square().mean())
    value.backward()
    for name,p in net.named_parameters():
        if ("raw_layers.0.slot_queries" in name or
            "shape_layers.0.slot_queries" in name or
            "raw_layers.0.router" in name or
            "shape_layers.0.router" in name):
            if p.grad is None or p.grad.abs().sum().item()==0:
                raise AssertionError(f"Missing mechanism router gradient: {name}")
    return True


def benchmark(args):
    numerical_tests()
    train,test,y,yt,_=load_data(args.dataset)
    classes=np.unique(y)
    outpath=Path(args.out);outpath.mkdir(parents=True,exist_ok=True)
    output=[]
    fit_info=[]
    for seed in args.seeds:
        started=time.monotonic()
        models={}
        for name,mechanism,attention in (
            ("generic",False,"routed"),
            ("mesa",True,"routed"),
            ("dense",False,"dense")):
            net,curve=fit_ssl(train,seed+9000,mechanism,attention,
                              args.epochs,args.dim,args.depth)
            models[name]=net
            fit_info.append(dict(dataset=args.dataset,seed=seed,name=name,
                epochs=args.epochs,params=sum(p.numel() for p in net.parameters()),
                losses=curve))
        if args.cnn_baseline:
            old,loss=train_ssl(train,seed+9000,mechanism=True,
                               epochs=args.epochs,hidden=40,dim=args.dim)
            models["cnn"]=old
            fit_info.append(dict(dataset=args.dataset,seed=seed,name="cnn",
                epochs=args.epochs,params=sum(p.numel() for p in old.parameters()),
                losses=loss))
        views,queries,concepts=features(train,test,seed,models)
        idx=indices_for_seed(y,seed,budget=args.budget)
        K=build_kernels(views,idx)
        picks={}
        for family in ("Raw MultiRocket","Canonical MultiRocket","Dual MultiRocket",
                       "Generic learned-only","MESA learned-only",
                       "Generic dual-path hybrid","MESA dual-path hybrid"):
            picks[family]=fit_candidates(K,idx,y,classes,family)
        extra={
          "Dense-attention learned-only":model_candidates("dense"),
          "Dense-attention hybrid":model_candidates("dense",True),
        }
        if args.cnn_baseline:
            extra["CNN MESA learned-only"]=model_candidates("cnn")
            extra["CNN MESA hybrid"]=model_candidates("cnn",True)
        for name,patterns in extra.items():
            picks[name]=custom_fit(K,idx,y,classes,patterns)
        predictions={name:predict(model,K) for name,model in picks.items()}
        predictions["RouterFormer learned-only"]=predictions["MESA learned-only"]
        predictions["RouterFormer hybrid"]=predictions["MESA dual-path hybrid"]
        predictions["RouterFormer dual-chart"],chart_meta=two_chart_policy(
            concepts[0],concepts[1:3],concepts[3:],
            queries,picks,K,idx,y,classes,seed,restricted=True)
        clean_candidates=("Raw MultiRocket","Canonical MultiRocket",
            "Dual MultiRocket","Generic dual-path hybrid",
            "MESA dual-path hybrid","Dense-attention hybrid")
        name=min(clean_candidates,key=lambda n:(
            -picks[n]["objective"],len(picks[n]["weights"]),n))
        predictions["TRAIN-selected admissible"]=predict(picks[name],K)
        if not args.cnn_baseline:
            methodset=tuple(m for m in METHODS if "CNN" not in m)
        else:
            methodset=METHODS
        for method in methodset:
            scores=predictions[method]
            pred=[classes[np.argmax(z,axis=1)] for z in scores]
            is_alias=(method=="RouterFormer learned-only" or method=="RouterFormer hybrid")
            model_key=("MESA learned-only" if method=="RouterFormer learned-only"
                       else "MESA dual-path hybrid" if method=="RouterFormer hybrid"
                       else method)
            selected=picks.get(model_key)
            row=dict(dataset=args.dataset,seed=seed,method=method,status="EXECUTED",
                clean_macro_f1=float(f1_score(yt,pred[0],average="macro",zero_division=0)),
                affine_macro_f1=float(f1_score(yt,pred[1],average="macro",zero_division=0)),
                jitter_macro_f1=float(f1_score(yt,pred[2],average="macro",zero_division=0)),
                n_train=len(train),n_test=len(test),n_labeled=len(idx),
                epochs=args.epochs,dim=args.dim,depth=args.depth,
                cv_objective=selected["objective"] if selected else None,
                weights=selected["weights"] if selected else None,
                selected_expert=name if method=="TRAIN-selected admissible" else None,
                chart_policy=chart_meta if method=="RouterFormer dual-chart" else None,
                synthetic_nuisance_assumption="Both TEST perturbations assumed label preserving",
                elapsed_seconds=round(time.monotonic()-started,2))
            output.append(row)
            print("RESULT_JSON="+json.dumps(row,allow_nan=False),flush=True)
        (outpath/"results.json").write_text(json.dumps(output,indent=2))
        (outpath/"training.json").write_text(json.dumps(fit_info,indent=2))
    expected=len(args.seeds)*(len(METHODS) if args.cnn_baseline else len(METHODS)-2)
    if len(output)!=expected:raise AssertionError(f"Missing records: {len(output)} vs {expected}")
    return output


