#!/usr/bin/env python3
"""MESA-RouterFormer: a mechanism-routed, dual-stream, multiscale attention
encoder for few-label time-series representation learning.

Architecture:
  x -> exact affine decomposition x=(mean+slope*time+residual_rms*shape)
      -> raw and canonical multiscale tokens at 8/16/24 temporal bins
      -> separate local-window attention and compressed global memory slots
      -> analytic concept-conditioned mixture of the two attention routes
      -> gated token pooling and independently inspectable raw/shape latents.

The shape stream's router consumes ONLY statistics derived from the canonical
residual: it is invariant to additive constant/trend, while the raw stream
retains discriminative mean/slope. A vanilla dense-attention control and a
matched zero-mechanism-loss router are evaluated at identical training budgets.

This is an experimental architecture, not a verified new state of the art.
Model selection uses labeled TRAIN only. TEST labels are used only for final
reporting. Synthetic corruption is assumed to preserve labels.

Academic provenance: Kim Phuc Tran, independent MESA_SSL research repository.
"""
